def fetch(url_or_path, data=None):
    """Bytes from a local file or a URL."""
    if data is None and Path(url_or_path).exists():
        return Path(url_or_path).read_bytes()
    print(f"Downloading {url_or_path} ...")
    req = urllib.request.Request(url_or_path, data=data, headers={"User-Agent": "gm-map-builder"})
    try:
        with urllib.request.urlopen(req, timeout=600) as resp:
            return resp.read()
    except urllib.error.URLError as e:
        # macOS's bundled Python links an old LibreSSL that some servers' TLS rejects; curl copes.
        if not isinstance(e.reason, ssl.SSLError):
            raise
        cmd = ["curl", "-sSf", "-m", "600", "-A", "gm-map-builder", url_or_path]
        if data is not None:
            cmd += ["--data-binary", "@-"]
        return subprocess.run(cmd, input=data, capture_output=True, check=True).stdout


def read_csv(raw_or_zip, name=None):
    """DictReader over CSV bytes, or over a file inside a ZipFile."""
    if name:
        f = io.TextIOWrapper(raw_or_zip.open(name), encoding="utf-8-sig", newline="")
    else:
        f = io.StringIO(raw_or_zip.decode("utf-8-sig"), newline="")
    return csv.DictReader(f)


def gtfs_seconds(hhmmss):
    h, m, s = (int(x) for x in hhmmss.split(":"))
    return h * 3600 + m * 60 + s  # may exceed 24h for after-midnight trips


def slug(name):
    return "".join(c if c.isalnum() else "-" for c in name.lower()).strip("-")


def write_js(path, assignment, data):
    """Write `<assignment> = <json>;` with a do-not-edit header."""
    import json
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"// Generated by tools/{Path(__import__('sys').argv[0]).name}. Do not edit by hand.\n"
        f"{assignment} = {json.dumps(data, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
